def _yearbook_series_record(region: str, year: int) -> dict:
    index = year - 2015
    total_population = _to_people(YEARBOOK_TOTAL_POPULATION_10K[region][index])
    male_sample, female_sample, birth_2024, death_2024, aging_65_sample = YEARBOOK_2024_SAMPLE[region]
    sample_total = male_sample + female_sample
    male_population = int(round(total_population * male_sample / sample_total))
    female_population = total_population - male_population
    birth_delta = NATIONAL_BIRTH_DEATH_TREND[year][0] - NATIONAL_BIRTH_DEATH_TREND[2024][0]
    death_delta = NATIONAL_BIRTH_DEATH_TREND[year][1] - NATIONAL_BIRTH_DEATH_TREND[2024][1]
    birth_rate = max(0, round(birth_2024 + birth_delta, 2))
    death_rate = max(0, round(death_2024 + death_delta, 2))
    natural_growth_rate = round(birth_rate - death_rate, 2)
    aging_2024 = aging_65_sample / sample_total * 100 if sample_total else 0
    aging_delta = NATIONAL_65_PLUS_RATE[year] - NATIONAL_65_PLUS_RATE[2024]
    aging_rate = max(0, round(aging_2024 + aging_delta, 2))
    source_year = 2025 if year == 2024 else "2025及历年"
    return {
        "region": region,
        "year": year,
        "total_population": total_population,
        "male_population": male_population,
        "female_population": female_population,
        "birth_rate": birth_rate,
        "death_rate": death_rate,
        "natural_growth_rate": natural_growth_rate,
        "aging_rate": aging_rate,
        "urbanization_rate": YEARBOOK_URBANIZATION_RATE[region][index],
        "remarks": (
            "依据《中国统计年鉴2025》人口章节2-5、2-6十年序列表整理总人口和城镇化率；"
            "性别结构按2024年2-9样本结构折算，老龄化率按65岁及以上口径结合全国趋势折算，"
            "出生率、死亡率按2024年地区差异和全国年度趋势折算。"
        ),
        "aging_rate_basis": "65_plus",
        "data_source_name": f"中国统计年鉴{source_year}人口章节",
        "source_url": "https://www.stats.gov.cn/sj/ndsj/2025/indexch.htm",
        "data_quality": "official_yearbook_series_derived",
    }


